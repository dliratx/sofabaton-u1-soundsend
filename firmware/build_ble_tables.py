"""Generate CRC24/BLE and byte-whitening tables; no device access.

Bluetooth Core Vol6 PartB3.1.1/3.2; primary sample vectors are tested
independently in test_ble_packet_arm.py. Tables reduce CONNECT_IND work
inside the150us response window on this Cortex-M0.
"""
from pathlib import Path

def generate():
    crc=[];white=[]
    for i in range(256):
        s=i
        for _ in range(8):s=(s>>1)^(0xDA6000 if s&1 else 0)
        crc.append(s)
    for i in range(128):
        s=i;b=0
        for bit in range(8):
            if s&1:b|=1<<bit;s^=0x88
            s>>=1
        white.append(b|(s<<8))
    reverse=[int(f'{i:08b}'[::-1],2) for i in range(256)]
    rows=['/* Generated by build_ble_tables.py. Bluetooth Core Vol6 PartB3. */']
    for ctype,name,values in [('uint32_t','crc_table',crc),('uint16_t','white_table',white),('uint8_t','reverse_table',reverse)]:
        rows.append(f'static const {ctype} {name}[{len(values)}]={{')
        for i in range(0,len(values),8):rows.append('    '+','.join(hex(v) for v in values[i:i+8])+',')
        rows.append('};')
    Path(__file__).with_name('ble_packet_tables.h').write_text('\n'.join(rows)+'\n')

if __name__=='__main__':generate()
